// final/scripts/generate-favicons.js
// 🚨 FIX APPLIED: Using default imports (pkg and imageAdapterPkg) for CommonJS modules.

import * as fs from 'fs/promises'; 
import * as path from 'path';
// --- CORRECTED IMPORTS START ---
import pkg, { IconTransformationType } from '@realfavicongenerator/generate-favicon';
import imageAdapterPkg from "@realfavicongenerator/image-adapter-node";

// Destructure the functions and types needed from the default imports
const { 
    FaviconSettings, 
    MasterIcon, 
    generateFaviconFiles, 
    generateFaviconHtml
} = pkg;
const { 
    getNodeImageAdapter, 
    loadAndConvertToSvg 
} = imageAdapterPkg;
// --- CORRECTED IMPORTS END ---


// --- CONFIGURATION ---
// 1. INPUT: Path to your master SVG icon.
const MASTER_ICON_PATH = "src/assets/logo.svg"; 
// 2. OUTPUT: Physical directory where files are saved (matches the URL path /final/)
const OUTPUT_DIR = path.join(process.cwd(), "public", "final"); 
// ---------------------

async function runFaviconGeneration() {
    try {
        console.log("Starting favicon generation for Thar-Web...");
        
        // 1. Initialize image processing adapter
        const imageAdapter = await getNodeImageAdapter();

        // 2. Load the master icon
        // Note: We use 'as MasterIcon' here only for TypeScript type clarity, 
        // the code runs fine without it in a pure JS file.
        const masterIcon = {
            icon: await loadAndConvertToSvg(MASTER_ICON_PATH),
        };

        // 3. Define settings (using your updated values)
        // Note: The 'FaviconSettings' type annotation is removed here for simplicity 
        // as it's not strictly necessary for execution.
        const faviconSettings = {
            icon: {
                desktop: {
                    regularIconTransformation: {
                        type: IconTransformationType.None,
                    },
                    darkIconType: "regular",
                    darkIconTransformation: {
                        type: IconTransformationType.None,
                    },
                },
                touch: {
                    transformation: {
                        type: IconTransformationType.Background,
                        backgroundColor: "#ffffff",
                        backgroundRadius: 0,
                        imageScale: 1,
                    },
                    appTitle: "Thar-Web" 
                },
                webAppManifest: {
                    transformation: {
                        type: IconTransformationType.Background,
                        backgroundColor: "#ffffff",
                        backgroundRadius: 0,
                        imageScale: 1,
                    },
                    backgroundColor: "#ffffff",
                    themeColor: "#ffffff", 
                    name: "Thar-Web", 
                    shortName: "MySite"
                }
            },
            path: "/final/", // This is the public URL path
        };

        // 4. Generate and save files
        const files = await generateFaviconFiles(masterIcon, faviconSettings, imageAdapter);
        await fs.mkdir(OUTPUT_DIR, { recursive: true });
        for (const file of files) {
            const filePath = path.join(OUTPUT_DIR, file.fileName);
            await fs.writeFile(filePath, file.contents);
        }
        console.log(`✅ Generated ${files.length} favicon files into public/final/`);
        
        // 5. Generate HTML and save as an Astro component
        const html = await generateFaviconHtml(faviconSettings);
        const htmlComponentPath = path.join(process.cwd(), "src", "components", "FaviconTags.astro");
        
        const astroComponentContent = `
---
// This file is auto-generated by the favicon script. DO NOT EDIT MANUALLY!
---
<Fragment set:html={\`${html}\`} />
        `;
        await fs.writeFile(htmlComponentPath, astroComponentContent);
        console.log(`✅ Generated HTML markup saved to ${htmlComponentPath}`);

    } catch (error) {
        console.error("❌ Favicon generation failed:", error);
        console.error("HINT: 1. Is your logo.svg file located at src/assets/logo.svg?");
        console.error("2. Have you ensured the 'scripts/' folder is in your project root?");
        process.exit(1);
    }
}

runFaviconGeneration();